/** The template's title and body in `language`, with today's date filled in. */
export function fillTemplate(template: NoteTemplate, language: string, locale: string): { title: string; body: string } {
  const text = language.startsWith('th') ? template.th : template.en;
  const date = new Date().toLocaleDateString(locale, { day: 'numeric', month: 'short', year: 'numeric' });
  return { title: text.title.replace(/\{date\}/g, date), body: text.body.replace(/\{date\}/g, date) };
}

export function templateName(template: NoteTemplate, language: string): string {
  return language.startsWith('th') ? template.th.name : template.en.name;
}
