/** Adds the strings to i18next (merged under safeSpend, keeping the title). Safe to call more than once. */
export function registerSafeSpendStrings(): void {
  for (const [language, strings] of [['en', safeSpendEn], ['th', safeSpendTh]] as const) {
    i18n.addResourceBundle(language, 'translation', { safeSpend: strings }, true, false);
  }
}
